create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  customer_name text not null,
  customer_cep text not null,
  customer_city text not null default '',
  customer_note text not null default '',
  items jsonb not null default '[]'::jsonb,
  subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  shipping_cost numeric(10,2),
  total numeric(10,2),
  status text not null default 'Novo pedido'
    check (status in ('Novo pedido','Em atendimento','Aguardando pagamento','Pago','Em preparação','Enviado','Concluído','Cancelado')),
  admin_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.orders enable row level security;
grant usage, select on sequence public.orders_id_seq to anon, authenticated;
grant insert on public.orders to anon, authenticated;
grant select, update on public.orders to authenticated;

drop policy if exists "Customers can create orders" on public.orders;
create policy "Customers can create orders"
on public.orders for insert to anon, authenticated
with check (
  length(trim(customer_name)) between 1 and 160
  and length(trim(customer_cep)) between 8 and 9
  and jsonb_typeof(items) = 'array'
  and jsonb_array_length(items) between 1 and 100
  and subtotal >= 0
);

drop policy if exists "Admins can view orders" on public.orders;
create policy "Admins can view orders"
on public.orders for select to authenticated
using (public.is_store_admin());

drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
on public.orders for update to authenticated
using (public.is_store_admin())
with check (public.is_store_admin());

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);
